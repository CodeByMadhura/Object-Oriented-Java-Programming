public class PrintNumbers{

public static void main(String[] args){

int i = 1;

System.out.println("Using For Loop: ");

for(i = 1; i <= 50; i++){

System.out.print(i + " ");

}
System.out.println(" ");
System.out.println("Using While Loop: ");

i = 1;

while(i <= 50){

System.out.print(i + " ");
i++;

}

}

}